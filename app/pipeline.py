"""One debate turn = the closed loop (thesis 4.8.1).

Every turn is adaptive: diagnosis -> intervention -> targeted opponent reply.
It runs as a CrewAI crew (app/crew_flow.py) by default; ORCHESTRATOR=python runs the same logic as plain
functions (app/agents.py). Both runners need a real LLM backend (Ollama or an OpenAI compatible API).
No control arms and no canned replies: the thesis (Section 7.12) has no control group.
"""
import os
import time

from . import agents
from .validation import ValidationError, soft_flags, validate

DISCLAIMER = "Scores and diagnoses are generated by AI and may contain errors. They are practice feedback, not a grade."


def process_turn(db, llm, session_id, argument, orchestrator=None):
    sess = db.get_session(session_id)
    if not sess:
        raise KeyError("session not found")
    if sess.get("status") == "ended":      # Table 6.1 'Session validation': only an active session accepts arguments
        raise ValidationError("This debate session has ended. Please start a new debate.")
    topic, side = sess["topic"], sess["student_side"]
    history = db.previous_arguments(session_id)
    clean = validate(argument, topic, history)
    previous = db.last_turn(session_id)
    prev_weak = previous["weakness"] if previous else None
    orch = (orchestrator or os.getenv("ORCHESTRATOR", "crewai")).lower()
    use_crew = orch == "crewai" and hasattr(llm, "complete")
    t0 = time.time()

    def finish(analysis, scores, diagnosis, intervention, reply, fallback, fb, latency):
        number = db.next_turn_number(session_id)
        tid = db.save_turn(session_id, number, clean, analysis, scores, diagnosis, intervention, reply, fb,
                           fallback, latency=latency, orchestrator="crewai" if use_crew else "python")
        return tid, number

    if use_crew:
        from . import crew_flow
        c = crew_flow.run_turn(db, llm, session_id, topic, side, history, clean, previous, finish)
        analysis, scores, diagnosis = c["analysis"], c["scores"], c["diagnosis"]
        intervention, reply, used_fallback = c["intervention"], c["reply"], c["fallback"]
        fb, progress, tid, number = c["feedback"], c["progress"], c["tid"], c["number"]
        timings = c["timings"]
    else:
        analysis = agents.analyse(llm, topic, side, history, clean)
        scores = agents.score(llm, topic, side, analysis, clean)
        diagnosis = agents.diagnose(scores, clean, analysis, llm=llm, topic=topic, side=side)
        repeats = sum(1 for h in db.history(session_id) if h["weakness"] == diagnosis["lowest_weakness"])
        intervention = agents.strategise(diagnosis, prev_weak, repeats)
        reply, used_fallback = agents.oppose(llm, topic, side, clean, analysis, diagnosis, intervention,
                                             convo=db.conversation(session_id))
        fb = agents.feedback(scores, diagnosis)
        tid, number = finish(analysis, scores, diagnosis, intervention, reply, used_fallback, fb,
                             round(time.time() - t0, 1))
        progress = agents.track(scores, diagnosis, previous)
        timings = {"total": round(time.time() - t0, 1)}

    return {"turn_id": tid, "turn_number": number, "analysis": analysis, "scores": scores, "diagnosis": diagnosis,
            "intervention": intervention, "ai_opponent_response": reply, "guardrail_fallback": used_fallback,
            "feedback": fb, "progress": progress, "display": "full", "mode": "adaptive",
            "orchestrator": "crewai" if use_crew else "python", "timings": timings, "disclaimer": DISCLAIMER,
            "validation_flags": soft_flags(clean, topic, analysis)}